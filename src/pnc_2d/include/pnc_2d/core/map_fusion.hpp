// 把**全局静态图**的占据并进局部图：局部 = 局部 ∪ 全局。
//
// == 它解决什么问题（用户 2026-09-29 定的口径）==
// **2D 导航下"能不能过"必须由整套图一致决定，局部层不得比全局层宽松。**
//
// 局部图来自实时感知（滑动窗 + 高度带投影 + 车体 footprint 抹空闲），全局图来自
// PCD 离线投影。两者对同一块"货柜/货架"可能给出**相反**结论 —— 感知漏掉高处结构
// ⇒ 局部以为能钻过去，而全局说不能走。更普遍地：感知只看得到**它看过的地方**
// （滚动窗口 + max_ray_length），窗口外/未观测区它一无所知，而全局图对整站是
// 完整的。不融合时：全局规划器给的路是绕开的，但局部层可以自己"抄近路"穿过去，
// 而且它自己看不到任何矛盾。
//
// 融合之后：车体轮廓与"全局认为不可通行"的格子重叠 ⇒ 现有的 footprint 硬判定
// 直接判死，语义与全局一模一样（全局也是把障碍烧进图）。这和**禁行区**的处理
// 完全同构（`map_zones.hpp::burnForbidden`）—— 那条路 2026-09-23 已经做过并验证。
//
// == 三条必须讲清楚的语义（都会影响判定，写清楚免得被"优化"掉）==
//  1. **只做"占据"方向的 OR**：输出 = 局部原值，遇全局占据则置占据。
//     不把未知变空闲、也不把空闲变未知 —— 未知语义（感知保留 -1、全局
//     `unknown_as_free` 后没有 -1）各自沿用既有策略，融合不掺和。
//  2. **保守重采样**：局部格只要与**任一**占据的源格重叠 ⇒ 判占据。
//     全局 0.05 → 局部 0.10 是降采样，用"格中心点采样"会漏掉窄障碍（立柱、
//     桌腿、栏杆），那正是最需要拦住车的东西。代价是障碍边界最多外扩一个局部
//     格（10 cm）—— 方向是保守的，可以接受。
//  3. **只处理交叠区**：源图落在目标几何之外的部分不产生任何影响
//     （不扩大目标窗口、也不改它的 origin）。
//
// ⚠ 与"膨胀"的关系：全局图（map_server）**已经把 `inflate` 烧进去了**（0.05 m）。
//   所以融进来的障碍边界比真实几何大 5 cm —— 这与全局规划器自己的安全保证同源
//   （它也是在这张图上搜的），因此**是刻意保留的**，不要在融合里反向补偿。
//
// 坐标系：两边都可能带 origin yaw，所以一律走**世界系**（格 → 世界 → 源图格）。

#pragma once

#include <cstdint>
#include <cstddef>
#include <vector>

namespace pnc_2d {

class CostMap2D;

/// 把源图里的**占据格**保守投影到目标几何上。
///
/// @param src                源图（通常是被融合进来的全局图）
/// @param dst                目标几何（通常是局部图，决定 mask 的尺寸/origin/分辨率）
/// @param occupied_threshold 占据判定阈值（OccupancyGrid 约定：`>= 50` 即占据；
///                           传 100 只认"确定占据"）
/// @param mask               输出：与 `dst` 同尺寸，`100` = 该格与源图占据格有重叠，
///                           否则 `0`（不是 -1：这是"是否被并入占据"的掩码，不是占据图）
/// @return 标记的格数（0 = 源图与目标几何没有交叠出任何障碍）
std::size_t projectOccupancy(const CostMap2D &src, const CostMap2D &dst,
                             int occupied_threshold,
                             std::vector<int8_t> &mask);

/// 占据方向取并：`out = dst.data() ∪ mask`。
///
/// 语义细节：只有"`mask` 说占据、而 `dst` 原本**不是**占据"的格子会被改写
/// （改写成 `100`），并计入返回值 —— 这样返回值就是"全局图**新增**了哪些障碍"，
/// 一眼能看出融合有没有真的起作用（0 = 全局图没带来新障碍）。
/// `dst` 原本的 `-1/0` 一律原样保留。
///
/// @param out 先被填成 `dst.data()`，再在副本上做 OR
/// @return 新增为占据的格数
std::size_t fuseOccupancyMask(const CostMap2D &dst,
                              const std::vector<int8_t> &mask,
                              int occupied_threshold, std::vector<int8_t> &out);

} // namespace pnc_2d
